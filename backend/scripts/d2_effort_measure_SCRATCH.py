"""
SCRATCH - Sprint 9 D2 effort measurement. Not production code; lives outside
app/ and changes nothing in it. Reads the database (project 7's context) and
writes nothing to it. Writes only to the OS temp folder (blind-read files).

STATUS: registration v3 approved by the advisors and by the Project Lead (the
cap rule is approved as a FORMULA only; any actual cap value needs the Project
Lead's separate approval after seeing the results). Do not edit this file
after seeing results.

REVISED 2026-10-23, before any call was made: added the abort-after-run-1 check
and the multi-create warning, and applied the Project Lead's two decisions
(the outcome 4 fallback and the wording for medium hitting 16,000). Nothing
else changed.

REGISTRATION v3 (as approved)

Calls: six, alternating default and medium effort (D, M, D, M, D, M), through
the PRODUCTION path: run_reasoning -> generate_guidance -> build_prompt ->
anthropic_provider.send_prompt -> client.messages.create. A recording proxy
replaces anthropic.Anthropic for the process. For every call it rewrites ONLY
max_tokens (to 16,000) and, for the medium arm, adds
output_config={"effort": "medium"}. The default arm's request must have
exactly the production keys (model, max_tokens, messages); if it does not,
the script exits BEFORE any call is made. The provider file is not edited.
Usage is recorded BEFORE the provider can raise, so a run that stops at
16,000 is still recorded.

Inputs: the same as V5 run 1: the screw-jack message with project 7's
retrieval context (expected 3 lines), built by the same
build_retrieved_context the chat path uses. The context and its line count
are printed at the start. If the probe's D2 text differs from the V5 message,
the script says so.

Record per call: total output tokens, thinking tokens, stop reason,
wall-clock, answer text length. The answer text of the FIRST completed
default run and the FIRST completed medium run is saved (only in outcomes 1
and 4) to randomly labelled files A and B in the OS temp folder; the label
key is in a separate file and is not printed.

A run HITS 16,000 if its stop reason is max_tokens or its output tokens are
16,000 or more. If a run hits, only that arm's remaining runs are skipped and
the other arm continues. If both arms have hit (or are rejected), stop
spending.

COMPLETED means: no exception and stop reason end_turn.

Operational rules not in the registration (reported, not decisions): a call
that fails for another reason is recorded as a non-completion and is not
retried by this script (the SDK's own default retries still apply inside the
call); 3 consecutive connection errors abort the run; an HTTP 400 on a medium
call marks the medium arm as rejected and skips its remaining runs. If the proxy captured no request in run 1 the script
exits (the proxy was bypassed); more than one create() call inside a single
run_reasoning prints a warning.

Cost guard: a conservative ceiling estimate prices every input and output
token at $10 per million. The script stops before a call if the running
estimate plus a worst-case next call would exceed $1.00. This is an estimate,
not billing.

Outcomes (registered meaning):
  1 Separated: every medium total is below every default total. Medium is a
    candidate; then the blind read, then V10 at medium.
  2 No difference shown at n=3: default stays, as the simpler option.
  3 (flag, may accompany 1 or 2) Default maximum above about 10,500: the cap
    rule then gives 16,384 or more. Reported with the numbers; the 120 s
    question is decided afterward by the Project Lead.
  4 Default hits 16,000, medium does not: medium is the only candidate,
    subject to the blind read and V10. If default's first run hits 16,000 there
    is no completed default answer to pair. Then Moses writes down the checks he
    would demand from a screw-jack design BEFORE opening the first completed
    medium answer, reads that answer alone against his list, and medium is
    rejected if it misses one he would demand. V10 stays the main gate.
  5 Both arms hit 16,000: stop spending; report as the streaming discussion.
  6 Medium rejected by the API: reported as is.
  (Medium hits 16,000 while default does not: medium is not a candidate
  (Project Lead's decision, 2026-10-23). The numbers are still printed.)

Cap rule, FORMULA ONLY (information, not a proposed cap): highest total in
the arm x 1.5, rounded up to the next multiple of 2,048, never below 10,240.
This measurement does NOT replace V5: adopting any setting needs a diff
review of the provider edit, a V2 re-run, and V5 (three UI runs) at the
chosen setting.

Usage (from backend/, venv active):
  python scripts\\d2_effort_measure_SCRATCH.py          (dry run: prints the plan, sends nothing)
  python scripts\\d2_effort_measure_SCRATCH.py --run    (spends; expected about $0.40-0.55)
"""

import argparse
import json
import logging
import math
import re
import secrets
import statistics
import sys
import tempfile
import time
from pathlib import Path

PROBE_CAP = 16000
ARM_ORDER = ("default", "medium", "default", "medium", "default", "medium")
D2_PROMPT = ("I need a hand-operated screw jack to lift 2 tonnes by 300 mm. "
             "Propose the screw, nut and handle design.")
EXPECTED_MODEL = "claude-sonnet-5"
EXPECTED_PROVIDER_CAP = 10240
EXPECTED_CONTEXT_LINES = 3
PRODUCTION_KEYS = {"model", "max_tokens", "messages"}
CEILING_USD = 1.00
USD_PER_MTOK = 10.0  # upper bound applied to every token
DEFAULT_HIGH = 10500
MARGIN = 1.5
ROUND_TO = 2048
CAP_FLOOR = 10240
ABORT_AFTER_CONSECUTIVE_CONN = 3
CONN_CLASSES = ("APIConnectionError", "APITimeoutError")
BLIND_DIR = Path(tempfile.gettempdir()) / "d2_effort_blind_SCRATCH"

STATE = {"arm": None, "captured": []}


# ---------------------------------------------------------------- the proxy

class _Messages:
    def __init__(self, inner):
        self._inner = inner

    def create(self, **kwargs):
        arm = STATE["arm"]
        kwargs = dict(kwargs)
        kwargs["max_tokens"] = PROBE_CAP
        if arm == "medium":
            kwargs["output_config"] = {"effort": "medium"}
        expected = set(PRODUCTION_KEYS) | ({"output_config"} if arm == "medium" else set())
        if set(kwargs) != expected:
            sys.exit(f"REQUEST SHAPE CHANGED before any spend: {arm} arm would send keys "
                     f"{sorted(kwargs)}, expected {sorted(expected)}. Stop and report.")
        rec = {"arm": arm, "keys": sorted(kwargs)}
        STATE["captured"].append(rec)  # recorded before the call, so an error still leaves a trace
        try:
            resp = self._inner.create(**kwargs)
        except Exception as exc:  # noqa: BLE001 - recorded, then re-raised for the provider
            rec["exc_cls"] = type(exc).__name__
            rec["status"] = getattr(exc, "status_code", None)
            rec["exc_msg"] = str(exc)[:300]
            raise
        usage = getattr(resp, "usage", None)
        details = getattr(usage, "output_tokens_details", None)
        content = getattr(resp, "content", None) or []
        rec["in"] = getattr(usage, "input_tokens", None)
        rec["out"] = getattr(usage, "output_tokens", None)
        rec["think"] = getattr(details, "thinking_tokens", None)
        rec["stop"] = getattr(resp, "stop_reason", None)
        rec["blocks"] = [getattr(b, "type", "?") for b in content]
        rec["text"] = "".join(b.text for b in content if getattr(b, "type", None) == "text")
        return resp


class _Client:
    def __init__(self, real):
        self.messages = _Messages(real.messages)


def install_proxy(prov):
    real_cls = prov.anthropic.Anthropic

    def factory(*args, **kwargs):
        return _Client(real_cls(*args, **kwargs))

    prov.anthropic.Anthropic = factory
    return real_cls


# ------------------------------------------------------------ pure helpers

def is_hit(rec):
    out = rec.get("out")
    return rec.get("stop") == "max_tokens" or (out is not None and out >= PROBE_CAP)


def cap_formula(max_total):
    return max(CAP_FLOOR, math.ceil(max_total * MARGIN / ROUND_TO) * ROUND_TO)


def render_answer(text):
    """Same formatting for both arms, so the file does not reveal which arm wrote it."""
    raw = text.strip()
    cleaned = re.sub(r"^```(?:json)?\s*|\s*```$", "", raw)
    try:
        data = json.loads(cleaned)
    except ValueError:
        return raw + "\n"
    if not isinstance(data, dict):
        return json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    parts = []
    for key, value in data.items():
        parts.append("## " + str(key))
        if isinstance(value, str):
            parts.append(value)
        else:
            parts.append(json.dumps(value, indent=2, ensure_ascii=False))
        parts.append("")
    return "\n".join(parts)


def classify(rows, medium_rejected):
    """Returns (lines, outcome_numbers). Pure: works on the recorded rows only."""
    comp = {a: [r for r in rows if r["arm"] == a and r["completed"]] for a in ("default", "medium")}
    hit = {a: any(r["hit"] for r in rows if r["arm"] == a) for a in ("default", "medium")}
    lines, outcomes = [], []

    if hit["default"] and hit["medium"]:
        outcomes.append(5)
        lines.append("OUTCOME 5: both arms hit 16,000. Stop spending; report this as the streaming discussion.")
    elif medium_rejected:
        outcomes.append(6)
        lines.append("OUTCOME 6: the API rejected the medium-effort request (HTTP 400). Reported as is.")
    elif hit["default"]:
        outcomes.append(4)
        lines.append("OUTCOME 4: default hit 16,000 (it needs more than 16k) and medium did not. "
                     "Medium is the only candidate, subject to the blind read and V10. "
                     "The cap rule cannot be computed for default.")
    elif hit["medium"]:
        lines.append("MEDIUM HIT 16,000 while default did not: medium is not a candidate "
                     "(Project Lead's decision). The numbers are above.")
    elif len(comp["default"]) < 3 or len(comp["medium"]) < 3:
        lines.append(f"INCOMPLETE: completed runs default={len(comp['default'])}, "
                     f"medium={len(comp['medium'])} (need 3 each). No outcome derived.")
    else:
        d = [r["out"] for r in comp["default"]]
        m = [r["out"] for r in comp["medium"]]
        if max(m) < min(d):
            outcomes.append(1)
            lines.append(f"OUTCOME 1: separated. Medium totals {sorted(m)} are all below default totals {sorted(d)}. "
                         "Medium is a candidate; next is the blind read, then V10 at medium.")
        else:
            outcomes.append(2)
            lines.append(f"OUTCOME 2: no difference shown at n=3 (default {sorted(d)}, medium {sorted(m)}). "
                         "Default stays, as the simpler option.")
        if max(d) > DEFAULT_HIGH:
            outcomes.append(3)
            lines.append(f"OUTCOME 3 (flag): default maximum {max(d)} is above about {DEFAULT_HIGH}. "
                         "The cap rule then gives 16,384 or more. Reported with the numbers; the 120 s "
                         "question is decided afterward by the Project Lead.")
    return lines, outcomes


def formula_lines(rows):
    out = []
    for arm in ("default", "medium"):
        if any(r["hit"] for r in rows if r["arm"] == arm):
            out.append(f"  {arm}: not computable (an arm run hit 16,000)")
            continue
        comp = [r for r in rows if r["arm"] == arm and r["completed"]]
        if not comp:
            out.append(f"  {arm}: no completed runs")
            continue
        mx = max(r["out"] for r in comp)
        per_tok = statistics.median(r["ms"] / r["out"] for r in comp if r["out"])
        cap = cap_formula(mx)
        out.append(f"  {arm}: highest total {mx} -> formula value {cap}; "
                   f"median {per_tok:.1f} ms per output token -> about {cap * per_tok / 1000:.0f} s at that value")
    return out


def write_medium_alone(rows):
    """Outcome 4 with no completed default run: the first completed medium answer, read alone."""
    got = next((r for r in rows if r["arm"] == "medium" and r["completed"]), None)
    if got is None:
        print("READ-ALONE: no completed medium run, so there is no answer to read.")
        return
    BLIND_DIR.mkdir(parents=True, exist_ok=True)
    path = BLIND_DIR / "answer_medium_alone.txt"
    path.write_text(render_answer(got["text"]), encoding="utf-8")
    print(f"\nREAD-ALONE file written to: {path}")
    print("  Before opening it, Moses writes down the checks he would demand from a screw-jack design.")
    print("  He then reads the answer against that list. If it misses one he would demand, medium is rejected.")
    print("  V10 stays the main gate.")


def write_blind_files(rows):
    """First completed default run and first completed medium run, random labels."""
    first = {}
    for arm in ("default", "medium"):
        got = next((r for r in rows if r["arm"] == arm and r["completed"]), None)
        if got is None:
            print(f"BLIND READ: no completed {arm} run, so no pair can be set up.")
            return
        first[arm] = got
    BLIND_DIR.mkdir(parents=True, exist_ok=True)
    arms = ["default", "medium"]
    secrets.SystemRandom().shuffle(arms)
    key_lines = []
    for label, arm in zip(("A", "B"), arms):
        (BLIND_DIR / f"answer_{label}.txt").write_text(render_answer(first[arm]["text"]), encoding="utf-8")
        key_lines.append(f"{label} = {arm} (run {first[arm]['run']})")
    (BLIND_DIR / "KEY_open_only_after_judging.txt").write_text("\n".join(key_lines) + "\n", encoding="utf-8")
    print(f"\nBLIND READ files written to: {BLIND_DIR}")
    print("  answer_A.txt and answer_B.txt. The label key is in a separate file and is NOT printed.")
    print("  Moses reads both and judges before the key is opened.")


# --------------------------------------------------------------- the run

def load_app():
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from app.ai.providers import anthropic_provider as prov  # noqa: E402
    from app.core.config import settings  # noqa: E402
    from app.db.session import get_session  # noqa: E402
    from app.reasoning.engine import run_reasoning  # noqa: E402
    from app.reasoning.retrieval import build_retrieved_context  # noqa: E402
    return prov, settings, get_session, run_reasoning, build_retrieved_context


def one_call(arm, context, run_reasoning):
    STATE["arm"] = arm
    STATE["captured"].clear()
    start = time.perf_counter()
    exc, structured = None, None
    try:
        result = run_reasoning(D2_PROMPT, retrieved_context=context)
        structured = getattr(result, "structured", None)
    except Exception as e:  # noqa: BLE001 - recorded, never crashes the run
        exc = e
    ms = int((time.perf_counter() - start) * 1000)
    rec = dict(STATE["captured"][-1]) if STATE["captured"] else {}
    row = {
        "arm": arm, "ms": ms, "in": rec.get("in"), "out": rec.get("out"), "think": rec.get("think"),
        "stop": rec.get("stop"), "text": rec.get("text", ""), "blocks": rec.get("blocks", []),
        "exc_cls": rec.get("exc_cls") or (type(exc).__name__ if exc else None),
        "exc_msg": rec.get("exc_msg") or (str(exc)[:300] if exc else None),
        "status": rec.get("status"), "schema": structured is not None,
        "creates": len(STATE["captured"]),
    }
    row["hit"] = is_hit(row)
    row["completed"] = exc is None and row["stop"] == "end_turn"
    return row


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--project-id", type=int, default=7)
    ap.add_argument("--run", action="store_true", help="actually call the API (spends money)")
    args = ap.parse_args()

    logging.basicConfig(level=logging.WARNING, format="%(levelname)s:%(name)s:%(message)s")
    prov, settings, get_session, run_reasoning, build_retrieved_context = load_app()

    if not settings.anthropic_api_key:
        sys.exit("ANTHROPIC_API_KEY is not configured.")
    if settings.anthropic_model != EXPECTED_MODEL:
        sys.exit(f"MODEL CHANGED: expected {EXPECTED_MODEL!r}, settings has {settings.anthropic_model!r}.")
    if prov.MAX_OUTPUT_TOKENS != EXPECTED_PROVIDER_CAP:
        sys.exit(f"PROVIDER CAP CHANGED: expected MAX_OUTPUT_TOKENS={EXPECTED_PROVIDER_CAP}, "
                 f"found {prov.MAX_OUTPUT_TOKENS}. Re-register before running.")
    print(f"environment OK: model={settings.anthropic_model}; provider MAX_OUTPUT_TOKENS={prov.MAX_OUTPUT_TOKENS}")

    try:
        import truncation_measure_SCRATCH as probe_prompts
        probe_d2 = next(p["prompt"] for p in probe_prompts.DESIGN_PROMPTS if p["id"] == "D2_screw_jack")
        print(f"D2 text matches the probe's D2: {probe_d2 == D2_PROMPT}"
              + ("" if probe_d2 == D2_PROMPT else "  <-- DIFFERS from the probe; report this"))
    except Exception as exc:  # noqa: BLE001
        print(f"(could not compare with the probe's D2: {type(exc).__name__}: {exc})")

    session = next(get_session())
    try:
        context = build_retrieved_context(session, args.project_id)
    finally:
        session.close()
    if context is None:
        sys.exit(f"No retrievable context for project {args.project_id}.")
    lines = [ln for ln in context.splitlines() if ln.strip()]
    print(f"\n=== INJECTED CONTEXT (project {args.project_id}; {len(lines)} lines) ===")
    print(context)
    print("=====================================")
    if len(lines) != EXPECTED_CONTEXT_LINES:
        sys.exit(f"Context has {len(lines)} lines, expected {EXPECTED_CONTEXT_LINES}. "
                 "It does not match V5 run 1's input. Stop and report.")

    print(f"\nprompt: {D2_PROMPT!r}")
    print(f"order: {', '.join(ARM_ORDER)}  |  cap {PROBE_CAP}  |  medium adds output_config={{'effort': 'medium'}}")
    print(f"cost ceiling {CEILING_USD:.2f} USD (conservative estimate, all tokens at ${USD_PER_MTOK:.0f}/M)")
    if not args.run:
        print("\nDRY RUN: nothing was sent to the API. Add --run to spend.")
        return

    saved = install_proxy(prov)
    rows, spent = [], 0.0
    skipped = {"default": False, "medium": False}
    run_no = {"default": 0, "medium": 0}
    medium_rejected, consecutive_conn, first_in = False, 0, 3000
    try:
        for arm in ARM_ORDER:
            if skipped[arm]:
                print(f"{arm:<8} SKIPPED (arm already hit 16,000 or was rejected)")
                continue
            if all(skipped.values()):
                break
            worst = (PROBE_CAP + first_in) * USD_PER_MTOK / 1e6
            if spent + worst > CEILING_USD:
                print(f"STOP: estimated spend {spent:.2f} + worst-case next call {worst:.2f} "
                      f"would exceed {CEILING_USD:.2f} USD.")
                break
            run_no[arm] += 1
            row = one_call(arm, context, run_reasoning)
            row["run"] = run_no[arm]
            rows.append(row)
            spent += ((row["in"] or 0) + (row["out"] or 0)) * USD_PER_MTOK / 1e6
            if row["in"]:
                first_in = row["in"]
            if len(rows) == 1 and row["creates"] == 0:
                sys.exit("PROXY BYPASSED: no request was captured in run 1, so the calls are not going "
                         "through the recording proxy. Stopped after one call. Report this.")
            if row["completed"]:
                consecutive_conn = 0
                print(f"{arm:<8} run{row['run']}  stop={row['stop']:<10} in={row['in']:<5} out={row['out']:<6} "
                      f"think={row['think']!s:<6} text_chars={len(row['text']):<6} schema={row['schema']!s:<5} "
                      f"{row['ms']:>7} ms  est_spend={spent:.2f}", flush=True)
            else:
                consecutive_conn = consecutive_conn + 1 if row["exc_cls"] in CONN_CLASSES else 0
                print(f"{arm:<8} run{row['run']}  NON-COMPLETION stop={row['stop']} out={row['out']} "
                      f"think={row['think']} exc={row['exc_cls']} status={row['status']} "
                      f"msg={(row['exc_msg'] or '')[:140]!r}  {row['ms']} ms  est_spend={spent:.2f}", flush=True)
            if row["creates"] > 1:
                print(f"  WARNING: {row['creates']} create() calls happened inside this one run_reasoning; "
                      "only the last is recorded above.")
            if row["hit"]:
                skipped[arm] = True
                print(f"  -> {arm} arm hit {PROBE_CAP}: its remaining runs are skipped.")
            if arm == "medium" and row["status"] == 400:
                medium_rejected = True
                skipped["medium"] = True
                print("  -> HTTP 400 on a medium call: medium arm marked rejected; its remaining runs are skipped.")
            if consecutive_conn >= ABORT_AFTER_CONSECUTIVE_CONN:
                print(f"ABORT: {consecutive_conn} consecutive connection errors.")
                break
    finally:
        prov.anthropic.Anthropic = saved

    print(f"\n=== SUMMARY: {len(rows)} calls sent; estimated spend {spent:.2f} USD (conservative estimate) ===")
    for arm in ("default", "medium"):
        for r in (x for x in rows if x["arm"] == arm):
            if r["completed"]:
                tag = f"total {r['out']} (thinking {r['think']}), {r['ms']} ms"
            elif r["hit"]:
                tag = f"HIT {PROBE_CAP}: total >= {PROBE_CAP} (censored; thinking {r['think']})"
            else:
                tag = f"non-completion ({r['exc_cls'] or r['stop']})"
            print(f"  {arm:<8} run{r['run']}: {tag}")
    lines_out, outcomes = classify(rows, medium_rejected)
    print()
    for ln in lines_out:
        print(ln)
    print("\nCap rule FORMULA values (information only; not a proposed cap; any cap value needs the "
          "Project Lead's separate approval):")
    for ln in formula_lines(rows):
        print(ln)
    if 1 in outcomes:
        write_blind_files(rows)
    elif 4 in outcomes:
        if any(r["arm"] == "default" and r["completed"] for r in rows):
            write_blind_files(rows)
        else:
            write_medium_alone(rows)
    print("\nThis measurement does not replace V5. No production file was changed.")


if __name__ == "__main__":
    main()
